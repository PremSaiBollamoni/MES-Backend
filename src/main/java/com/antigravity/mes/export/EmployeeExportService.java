package com.antigravity.mes.export;

import com.antigravity.mes.mail.MailSenderProvider;
import com.antigravity.mes.model.Employee;
import com.antigravity.mes.model.Factory;
import com.antigravity.mes.repository.EmployeeRepository;
import com.antigravity.mes.repository.FactoryRepository;
import jakarta.mail.internet.MimeMessage;
import org.apache.poi.ss.usermodel.*;
import org.apache.poi.xssf.usermodel.XSSFWorkbook;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.core.io.ByteArrayResource;
import org.springframework.mail.javamail.JavaMailSender;
import org.springframework.mail.javamail.MimeMessageHelper;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.io.ByteArrayOutputStream;
import java.security.SecureRandom;
import java.time.LocalDate;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;

/** Exports a factory's employee list as a spreadsheet, optionally after giving every employee
 * a new temporary password. Passwords are stored as one-way hashes, so the only way to put a
 * password in the sheet is to set a new one at the same time - the current passwords stop
 * working when that happens. */
@Service
public class EmployeeExportService {

    private static final DateTimeFormatter DATE_LABEL = DateTimeFormatter.ofPattern("dd MMM yyyy");
    // No look-alike characters (0/O, 1/l/I), so a password read out or typed by hand is unambiguous.
    private static final String PASSWORD_CHARS = "abcdefghjkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789";
    private static final int PASSWORD_LENGTH = 8;
    private static final String NOT_RESET = "(not reset)";

    private final SecureRandom random = new SecureRandom();

    @Autowired
    private EmployeeRepository employeeRepository;

    @Autowired
    private FactoryRepository factoryRepository;

    @Autowired
    private PasswordEncoder passwordEncoder;

    @Autowired
    private MailSenderProvider mailSenderProvider;

    public record EmployeeRow(int serial, String name, String username, String password) {}

    public record Export(String factoryName, byte[] xlsx, List<EmployeeRow> rows) {}

    @Transactional
    public Export export(Long factoryId, boolean resetPasswords) {
        Factory factory = factoryRepository.findById(factoryId)
                .orElseThrow(() -> new IllegalArgumentException("Factory not found"));

        // SUPER_ADMIN's own row carries a placeholder factory and is not a workforce member.
        List<Employee> employees = employeeRepository.findByFactoryId(factoryId).stream()
                .filter(e -> !e.hasActiveRoleNamed("SUPER_ADMIN"))
                .sorted(Comparator.comparing(Employee::getUsername))
                .toList();

        List<EmployeeRow> rows = new ArrayList<>();
        int serial = 1;
        for (Employee employee : employees) {
            String password = NOT_RESET;
            if (resetPasswords) {
                password = generatePassword();
                employee.setPasswordHash(passwordEncoder.encode(password));
                employee.setFailedLoginAttempts(0);
                employee.setLockedUntil(null);
                employeeRepository.save(employee);
            }
            rows.add(new EmployeeRow(serial++, employee.getName(), employee.getUsername(), password));
        }

        return new Export(factory.getFactoryName(), toXlsx(factory.getFactoryName(), rows, resetPasswords), rows);
    }

    /** Builds the export, then emails it. The attachment carries passwords in plain text, so the
     * email body says to share it only with the people who need it. */
    public void emailExport(Long factoryId, boolean resetPasswords, List<String> recipients) throws Exception {
        Export export = export(factoryId, resetPasswords);
        String filename = export.factoryName().replaceAll("[^A-Za-z0-9]+", "-") + "-employees-"
                + LocalDate.now() + ".xlsx";

        String body = "The employee list for " + export.factoryName() + " is attached (generated "
                + LocalDate.now().format(DATE_LABEL) + ").\n\n"
                + (resetPasswords
                    ? "Every employee has been given a new temporary password, shown in the Password column. "
                      + "Their previous passwords no longer work. Please share each password only with the employee it belongs to, "
                      + "and ask them to change it after signing in."
                    : "No passwords were changed for this export.")
                + "\n\nGenerated by SMO.";

        MimeMessage message = mailSenderProvider.current().createMimeMessage();
        MimeMessageHelper helper = new MimeMessageHelper(message, true, "UTF-8");
        helper.setTo(recipients.toArray(new String[0]));
        helper.setSubject(export.factoryName() + " - Employee List");
        helper.setText(body, false);
        helper.addAttachment(filename, new ByteArrayResource(export.xlsx()));
        mailSenderProvider.current().send(message);
    }

    private String generatePassword() {
        StringBuilder sb = new StringBuilder(PASSWORD_LENGTH);
        for (int i = 0; i < PASSWORD_LENGTH; i++) {
            sb.append(PASSWORD_CHARS.charAt(random.nextInt(PASSWORD_CHARS.length())));
        }
        return sb.toString();
    }

    private byte[] toXlsx(String factoryName, List<EmployeeRow> rows, boolean resetPasswords) {
        try (XSSFWorkbook workbook = new XSSFWorkbook()) {
            Sheet sheet = workbook.createSheet("Employees");
            sheet.setColumnWidth(0, 8 * 256);
            sheet.setColumnWidth(1, 32 * 256);
            sheet.setColumnWidth(2, 18 * 256);
            sheet.setColumnWidth(3, 24 * 256);

            Font boldFont = workbook.createFont();
            boldFont.setBold(true);
            CellStyle header = workbook.createCellStyle();
            header.setFont(boldFont);
            header.setFillForegroundColor(IndexedColors.LIGHT_GREEN.getIndex());
            header.setFillPattern(FillPatternType.SOLID_FOREGROUND);
            header.setBorderBottom(BorderStyle.THIN);

            Row title = sheet.createRow(0);
            title.createCell(0).setCellValue(factoryName + " - Employee List");
            title.getCell(0).setCellStyle(headerTitle(workbook));
            sheet.addMergedRegion(new org.apache.poi.ss.util.CellRangeAddress(0, 0, 0, 3));

            Row headerRow = sheet.createRow(2);
            String[] headers = {"S.NO", "Employee Name", "Username", "Password"};
            for (int col = 0; col < headers.length; col++) {
                Cell cell = headerRow.createCell(col);
                cell.setCellValue(headers[col]);
                cell.setCellStyle(header);
            }

            int rowIndex = 3;
            for (EmployeeRow data : rows) {
                org.apache.poi.ss.usermodel.Row line = sheet.createRow(rowIndex++);
                line.createCell(0).setCellValue(data.serial());
                line.createCell(1).setCellValue(data.name());
                line.createCell(2).setCellValue(data.username());
                line.createCell(3).setCellValue(data.password());
            }
            sheet.setAutoFilter(new org.apache.poi.ss.util.CellRangeAddress(2, 2, 0, 3));
            sheet.createFreezePane(0, 3);

            ByteArrayOutputStream out = new ByteArrayOutputStream();
            workbook.write(out);
            return out.toByteArray();
        } catch (java.io.IOException e) {
            throw new java.io.UncheckedIOException("Failed to build employee workbook", e);
        }
    }

    private CellStyle headerTitle(XSSFWorkbook workbook) {
        Font font = workbook.createFont();
        font.setBold(true);
        font.setFontHeightInPoints((short) 14);
        CellStyle style = workbook.createCellStyle();
        style.setFont(font);
        return style;
    }
}
